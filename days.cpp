#include <iostream>
using namespace std;

int main() {
    //nested if-else statement
int index = 7;

if(index==1){
 cout<<"monday"<<endl;
}
else if (index==2){
 cout<<"tuesday"<<endl;
}
else if (index==3){
 cout<<"wednesday"<<endl;
}
else if (index==4){
 cout<<"thursday"<<endl;
}
else if (index==5){
 cout<<"friday"<<endl;
}
else if (index==6){
 cout<<"saturday"<<endl;
}
else if(index==7){
 cout<<"sunday"<<endl;
}

 return 0;
}
